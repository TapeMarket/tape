// Owns an isolated Anvil, public fixture keys and mock USDC. Never connects to a funded chain.
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { readFile, mkdtemp, rm } from "node:fs/promises";
import { createServer } from "node:net";
import { tmpdir, homedir } from "node:os";
import { join } from "node:path";
import { createPublicClient, createWalletClient, getContractAddress, http } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { foundry } from "viem/chains";
import { createChain, createTxQueue } from "../src/chain.mjs";
import { createStore, createIndexer } from "../src/indexer.mjs";
import { createEngine } from "../src/engine.mjs";
import { createKeeper } from "../src/keeper.mjs";
import { createHub } from "../src/util.mjs";
import { createBook } from "../src/prices/book.mjs";
import { createHyperliquidSource } from "../src/prices/hyperliquid.mjs";
import { createExecutions, createExecutionSigner } from "../src/prices/execution.mjs";
import { domain, types } from "../../shared/eip712.mjs";

const deployer = privateKeyToAccount("0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80");
const operatorKey = "0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d";
const operator = privateKeyToAccount(operatorKey);
const trader = privateKeyToAccount("0x5de4111afa1a4b94908f83103eb1f1706367c2e68ca870fc3fb9a804cdab365a");
const signerKey = `0x${"11".repeat(32)}`;
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(fn, ms = 12000) { const end = Date.now() + ms; while (Date.now() < end) { const value = await fn(); if (value) return value; await sleep(20); } throw Error("Local rehearsal timed out"); }
const reserve = createServer(); await new Promise(resolve => reserve.listen(0, "127.0.0.1", resolve)); const port = reserve.address().port; await new Promise(resolve => reserve.close(resolve));
const rpcUrl = `http://127.0.0.1:${port}`;
const anvil = spawn(join(homedir(), ".foundry/bin/anvil.exe"), ["--host", "127.0.0.1", "--port", String(port), "--chain-id", "31337", "--block-time", "1", "--silent"], { windowsHide: true, stdio: "ignore" });
const dir = await mkdtemp(join(tmpdir(), "tape-fast-smoke-"));
const client = createPublicClient({ chain: foundry, transport: http(rpcUrl, { retryCount: 0, timeout: 2000 }) });
const wallet = createWalletClient({ account: deployer, chain: foundry, transport: http(rpcUrl) });
let source, keeper, indexer, ticker;
const log = { info() {}, warn: text => console.log("rehearsal:", text), error: (...args) => console.error("rehearsal:", ...args) };
try {
  await until(async () => { try { return await client.getChainId() === 31337; } catch { return false; } });
  const artifacts = new Map();
  const artifact = async name => {
    if (!artifacts.has(name)) artifacts.set(name, JSON.parse(await readFile(new URL(`../../${name === "FastExchange" || name === "ExecutionOracle" ? "deployable/fast" : "deployable"}/${name}.json`, import.meta.url), "utf8")));
    return artifacts.get(name);
  };
  artifacts.set("MockUSDC", JSON.parse(await readFile(new URL("../../out/Mocks.sol/MockUSDC.json", import.meta.url), "utf8")));
  const send = async (address, name, functionName, args) => client.waitForTransactionReceipt({ hash: await wallet.writeContract({ address, abi: (await artifact(name)).abi, functionName, args }), pollingInterval: 50 });
  const deploy = async (name, args = []) => {
    const a = await artifact(name);
    const receipt = await client.waitForTransactionReceipt({ hash: await wallet.deployContract({ abi: a.abi, bytecode: a.bytecode.object, args }), pollingInterval: 50 });
    assert.equal(receipt.status, "success"); return receipt.contractAddress;
  };
  const usdc = await deploy("MockUSDC"), pricing = await deploy("Pricing"), sessions = await deploy("Sessions", ["Tape"]);
  const nonce = await client.getTransactionCount({ address: deployer.address });
  const predicted = getContractAddress({ from: deployer.address, nonce: BigInt(nonce + 1) });
  const oracle = await deploy("ExecutionOracle", [predicted, privateKeyToAccount(signerKey).address]);
  const exchange = await deploy("FastExchange", ["Tape", usdc, oracle, pricing, sessions, deployer.address, deployer.address, 5_000_000000000n, 1_000000n]);
  assert.equal(exchange.toLowerCase(), predicted.toLowerCase());
  const lens = await deploy("Lens", [exchange]), batcher = await deploy("Batcher", [exchange]);
  await send(exchange, "FastExchange", "setOperator", [operator.address, true]);
  await send(exchange, "FastExchange", "setOperator", [batcher, true]);
  const feedId = `0x${Buffer.from("hyperliquid:BTC").toString("hex").padEnd(64, "0")}`;
  await send(exchange, "FastExchange", "listMarket", [feedId, "BTC", 1000, { rateMultiplier: 15000, positionMultiplier: 814598, tick: 10000000, bustBuffer: 476041580087574n, depth: 1_000_000 }, 9000, 50, 10_000_000000000n, 100_000_000000000n, 100_000_000000000n]);
  await send(usdc, "MockUSDC", "mint", [deployer.address, 1000_000000n]);
  await send(usdc, "MockUSDC", "approve", [exchange, 1000_000000n]);
  await send(exchange, "FastExchange", "depositFor", [trader.address, 1000_000000n]);
  const config = { root: new URL("../../", import.meta.url).pathname, chainId: 31337, rpcUrl, operatorKey, deployment: { name: "Tape", exchange, oracle, oracleKind: "signed", pricing, sessions, lens, batcher, usdc, gateway: exchange, block: 0, executionMode: "order-bound" }, executionMode: "order-bound", oracleKind: "signed", priceSource: "hyperliquid", dataDir: dir, pollMs: 50, rateLimit: 40, cashFloorUsd: 2_000_000, cashMultiple: 50, gasMinEth: 0, tipFloorGwei: 0.05, tipCapGwei: 3, bumpAfterMs: 15000, receiptPollMs: 50, stakerPushMinUsd: 1, stakerPushSeconds: 300 };
  const chain = createChain(config), store = createStore(), hub = createHub();
  const queue = createTxQueue({ chain, log, config, onSettled: () => { void indexer.tick(); } });
  indexer = createIndexer({ config, chain, store, hub, log }); await indexer.start();
  const book = createBook([0]), signer = createExecutionSigner({ privateKey: signerKey, chainId: 31337, oracle });
  source = createHyperliquidSource({ markets: store.markets, book, signer, orderBound: true, sanityBps: 0, log, fetchImpl: () => new Promise(() => {}) });
  const executions = await createExecutions({ dir, chainId: 31337, oracle, signer, source });
  const engine = createEngine({ config, chain, book, source, store, queue, hub, log, executions, onPricedOpen: id => keeper.rescan(id), onCloseReleased: id => keeper.rescan(id) });
  keeper = createKeeper({ config, chain, book, source, store, queue, engine, indexer, log }); keeper.start();
  let bid = "80000", ask = "80001";
  ticker = setInterval(() => source.ingest("BTC", bid, ask, Date.now()), 50);
  await until(() => book.latest(0));
  const typedDomain = domain("Tape", 31337, exchange);
  let salt = 0n;
  const openOrder = async () => {
    const intent = { owner: trader.address, market: 0, isLong: true, useQueued: false, leverage: 100, margin: 100_000000n, priceLimit: 0n, impactLimit: 0, timestamp: BigInt(Math.floor(Date.now() / 1000)), salt: ++salt };
    const signature = await trader.signTypedData({ domain: typedDomain, types, primaryType: "Open", message: intent });
    const start = performance.now(); const accepted = await engine.open({ intent, signature });
    const filled = await until(() => { const value = engine.intent(accepted.id); if (value.status === "failed") throw Error(value.error); return ["filled", "confirmed"].includes(value.status) ? value : null; });
    const elapsed = performance.now() - start;
    assert.ok(elapsed < 1000, `Unexpected fixed wait: ${elapsed}ms`);
    return { id: accepted.id, elapsed, filled };
  };
  const first = await openOrder();
  assert.ok(store.positions.get(first.id).entryAtMs > 0);
  bid = "80100"; ask = "80101";
  const closeIntent = { owner: trader.address, positionId: first.id, timestamp: BigInt(Math.floor(Date.now() / 1000)) };
  const signature = await trader.signTypedData({ domain: typedDomain, types, primaryType: "Close", message: closeIntent });
  const closeStart = performance.now(); const closing = await engine.close({ intent: closeIntent, signature });
  await until(() => { const value = engine.intent(closing.id); if (value.status === "failed") throw Error(value.error); return ["filled", "confirmed"].includes(value.status); });
  const closeMs = performance.now() - closeStart;
  await until(() => { const value = engine.intent(closing.id); if (value?.status === "failed") throw Error(value.error); return value?.status === "confirmed"; });
  await until(() => !store.positions.has(first.id));
  assert.equal((await chain.read("exchange", "getPosition", [first.id])).owner, "0x0000000000000000000000000000000000000000");
  console.log(JSON.stringify({ openPricingMs: Math.round(first.elapsed), closePricingMs: Math.round(closeMs), execDelay: Number(await chain.read("exchange", "EXEC_DELAY")), confirmedOpenAndClose: true }));
  bid = "80000"; ask = "80001";
  await sleep(100);
  const second = await openOrder();
  await until(() => engine.intent(second.id).status === "confirmed");
  const onchain = store.positions.get(second.id);
  assert.ok(onchain.entryAtMs > 0, "confirmed indexer retained the millisecond event");
  source.ingest("BTC", "78000", "78001", Date.now());
  await sleep(10);
  source.ingest("BTC", "80000", "80001", Date.now());
  await until(() => !store.positions.has(second.id));
  console.log("PASS: real operator queue and indexer close a recovered position at its earlier recorded bust touch.");
} finally {
  clearInterval(ticker); source?.stop(); keeper?.stop(); indexer?.stop(); anvil.kill();
  await new Promise(resolve => anvil.once("exit", resolve));
  await rm(dir, { recursive: true, force: true });
}
