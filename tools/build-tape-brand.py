"""Builds the Tape wordmark: a strip of label tape with the letters TAPE punched through it.

    python tools/build-tape-brand.py

The letters are Geist Mono at weight 800 (the bundled web/src/assets/fonts file, SIL OFL), turned into outlines so
the logo never depends on a font loading. The strip and the letters are one path with the even-odd rule, so the
letters are holes: on a white page they read white, on a photo they show the photo. Writes:
    web/src/components/Wordmark.tsx      the React wordmark + the square mark
    web/public/favicon.svg               the square mark
"""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import OverlapMode, instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "web/src/assets/fonts/geist-mono-latin-wght-normal.woff2"
BLUE = "#1640ff"

# REMOVE merges each letter's overlapping contours (needs skia-pathops), so the even-odd holes come out clean
font = instantiateVariableFont(TTFont(FONT), {"wght": 800}, overlap=OverlapMode.REMOVE)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm
cap = font["OS/2"].sCapHeight or 700


def letters(text, x0, baseline, size, track):
    """SVG path data for `text` with its baseline at y=`baseline`, `size` = cap height in px."""
    scale = size / cap
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    x = x0
    for ch in text:
        name = cmap[ord(ch)]
        g = glyphs[name]
        # font units are y-up: flip, scale, then move to the pen position
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
        x += g.width * scale + track
    return pen.getCommands(), x - track


# --- the wordmark: a 600 x 160 strip; left end cut in a V, right end cut on a slant
H, W = 160, 600
NOTCH = 26  # depth of the V on the left
SLANT = 22  # the right end leans
strip = f"M0 0H{W}L{W - SLANT} {H}H0L{NOTCH} {H / 2}Z"
size = 100  # cap height of the letters
# measure first, then centre the word in the strip (between the notch and the slant)
_, end = letters("TAPE", 0, 0, size, 8)
left = NOTCH + ((W - SLANT / 2) - NOTCH - end) / 2
word, _ = letters("TAPE", left, H / 2 + size / 2, size, 8)
WORD_D = f"{strip}{word}"

# --- the square mark (favicon, avatar): a short piece of tape with a punched T
S = 160
# The owner's own drawing of it (2026-10-16), traced: the strip and a plain centred T, with room around.
MARK_D = "M10 36.25H150L129.94 123.73H10L29.03 79.88ZM55.08 50.73H108.02V64.37H90.24V110.69H73.07V64.37H55.08Z"

tsx = f'''// Generated by tools/build-tape-brand.py. Do not edit by hand.

/** The Tape wordmark: a strip of label tape with TAPE punched through it (the letters are holes). */
export function Wordmark({{ height = 18, title = "Tape" }}: {{ height?: number; title?: string }}) {{
  return (
    <svg className="wordmark" viewBox="0 0 {W} {H}" height={{height}} role="img" aria-label={{title}}>
      <path fill="currentColor" fillRule="evenodd" d={{WORDMARK_PATH}} />
    </svg>
  );
}}

/** The square mark: a short piece of the same tape with a punched T. */
export function Mark({{ size = 24, title = "Tape" }}: {{ size?: number; title?: string }}) {{
  return (
    <svg className="mark" viewBox="0 0 {S} {S}" width={{size}} height={{size}} role="img" aria-label={{title}}>
      <path fill="currentColor" fillRule="evenodd" d="{MARK_D}" />
    </svg>
  );
}}

/** Width over height of the wordmark. */
export const WORDMARK_RATIO = {W / H:.4f};
export const BRAND_ACCENT = "{BLUE}";

/** The wordmark's outline (even-odd), in a {W} x {H} box: for drawing it on a canvas. */
export const WORDMARK_PATH = "{WORD_D}";
export const WORDMARK_SIZE: [number, number] = [{W}, {H}];
'''
(ROOT / "web/src/components/Wordmark.tsx").write_text(tsx, encoding="utf-8")
fav = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {S} {S}"><rect width="{S}" height="{S}" rx="32" fill="{BLUE}"/><path fill="#fff" fill-rule="evenodd" d="{MARK_D}"/></svg>\n'
(ROOT / "web/public/favicon.svg").write_text(fav, encoding="utf-8")
# a standalone preview of both, for looking at
(ROOT / "tools/out-tape-brand.svg").write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W + 220} {H + 40}"><rect width="100%" height="100%" fill="#fff"/>'
    f'<g transform="translate(20 20)"><path fill="{BLUE}" fill-rule="evenodd" d="{WORD_D}"/></g>'
    f'<g transform="translate({W + 50} 20)"><path fill="{BLUE}" fill-rule="evenodd" d="{MARK_D}"/></g></svg>\n',
    encoding="utf-8")
print("wrote Wordmark.tsx, favicon.svg, tools/out-tape-brand.svg")
